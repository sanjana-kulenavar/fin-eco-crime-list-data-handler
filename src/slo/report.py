def _gap_stats(con: duckdb.DuckDBPyConnection, d: date, target: str) -> dict:
    rows = con.execute(
        "SELECT entity_key, value, message FROM dq_issues WHERE rule_id = 'DQ050' AND source = ? AND snapshot_date = ?",
        [target, d],
    ).fetchall()
    days = [int(m.group(1)) for _, _, msg in rows if (m := re.search(r"; (\d+) days", msg))]
    programmes = [ref[:2] for _, ref, _ in rows if ref]
    by_prog: dict[str, int] = {}
    for p in programmes:
        by_prog[p] = by_prog.get(p, 0) + 1
    return {
        "count": len(rows),
        "median_days_since_un_listing": statistics.median(days) if days else None,
        "max_days": max(days) if days else None,
        "by_un_reference_prefix": dict(sorted(by_prog.items(), key=lambda kv: -kv[1])),
        "examples": [msg for _, _, msg in rows[:10]],
    }


def _issue_samples(con: duckdb.DuckDBPyConnection, d: date, path: Path) -> None:
    query_frame(
        con,
        """SELECT source, rule_id, severity, entity_key, field, value, message, fixed FROM (
             SELECT *, row_number() OVER (PARTITION BY source, rule_id ORDER BY entity_key, value) AS rn
             FROM dq_issues WHERE snapshot_date = $d) WHERE rn <= 50 ORDER BY source, rule_id, rn""",
        {"d": d},
    ).write_csv(path)


def _fix_examples(con: duckdb.DuckDBPyConnection, d: date) -> list[dict]:
    rows = query_frame(
        con,
        """SELECT source, rule_id, entity_key, before, after FROM (
             SELECT *, row_number() OVER (PARTITION BY source, rule_id ORDER BY entity_key, before) AS rn
             FROM fix_log WHERE snapshot_date = $d) WHERE rn <= 3 ORDER BY rule_id, source, rn""",
        {"d": d},
    )
    return rows.to_dicts()


def _top_issues(scorecard: dict, n: int = 5) -> list[dict]:
    rules = load_dq_rules()
    items = sorted(scorecard.get("issues_by_rule", {}).items(), key=lambda kv: -kv[1]["entities"])[
        :n
    ]
    return [{"rule_id": r, "title": rules[r]["title"], **v} for r, v in items]


def _fmt_pct(v: float | None) -> str:
    return "n/a" if v is None else f"{v:.1f}%"


def findings_markdown(summary: dict, image_prefix: str) -> str:
    d = summary["snapshot_date"]
    lines = [
        f"**Key findings, live run of {d}** (generated by `slo report`; every number comes from `data/reports/{d}/summary.json`)",
        "",
    ]
    sc = summary["sources"]
    lists = [s for s in ("eu", "un", "ofac", "uk", "nl") if s in sc and sc[s].get("records")]
    lines.append(
        "| List | Entities | Published | DQ score | Persons with full DOB | Persons with nationality | Open high-severity entities |"
    )
    lines.append("|---|---:|---|---:|---:|---:|---:|")
    for s in lists:
        c = sc[s]
        lines.append(
            f"| {s.upper()} | {c['records']:,} | {c.get('published_date') or 'n/a'} | {c['dq_score']} | "
            f"{_fmt_pct(c.get('pct_persons_full_dob'))} | {_fmt_pct(c.get('pct_persons_with_nationality'))} | "
            f"{c['open_entities_by_severity']['high']:,} |"
        )
    lines.append("")

    def n(rule: str, src: str) -> int:
        return sc.get(src, {}).get("issues_by_rule", {}).get(rule, {}).get("issues", 0)

    gaps = summary["crosslist"]["transposition_gaps"]
    cross = summary["crosslist"]["stats"]
    bullets = [
        f"**Placeholder and partial birth dates are the biggest data gap.** {n('DQ011', 'uk'):,} UK, {n('DQ011', 'eu'):,} EU and "
        f"{n('DQ011', 'ofac'):,} OFAC persons have only a year, month or range (DQ011). The UK publishes these as literal `dd/mm/YYYY` placeholders.",
        f"**Persons with no DOB at all (DQ010):** EU {n('DQ010', 'eu'):,}, UK {n('DQ010', 'uk'):,}, UN {n('DQ010', 'un'):,}, OFAC {n('DQ010', 'ofac'):,}.",
        f"**Country data:** {n('DQ020', 'eu'):,} EU country fields use code `00` (UNKNOWN). OFAC/UK have {n('DQ020', 'ofac') + n('DQ020', 'uk'):,} "
        "historical or unmappable values (e.g. `Serbia and Montenegro`, `USSR`, birth places with no country).",
        f"**Identifiers:** {n('DQ031', 'uk'):,} UK designations repeat the same passport/ID (DQ031). "
        f"{sum(n('DQ032', s) for s in lists):,} identifiers appear on two different entities in the same list (DQ032, possible duplicates).",
        f"**UN → EU / UK transposition:** {cross.get('un_eu', 0):,} of {cross.get('un_entities', 0):,} UN entities are found on the EU list, "
        f"{cross.get('un_uk', 0):,} on the UK list. Only {cross.get('linked_by_un_ref', {}).get('eu', 0)} of those EU matches could use a UN "
        f"reference published on the EU record; the rest were linked by name + DOB. {gaps['eu']['count']} UN entities have no EU match (median {gaps['eu']['median_days_since_un_listing']} days "
        f"since UN listing; by UN regime: {', '.join(f'{UN_REGIMES.get(k, k)} {v}' for k, v in list(gaps['eu']['by_un_reference_prefix'].items())[:4])}).",
        f"**Name hygiene fixed automatically:** {sum(n('DQ002', s) for s in lists):,} names with whitespace noise, "
        f"{sum(n('DQ004', s) for s in lists):,} empty alias elements, {sum(n('DQ005', s) for s in lists):,} duplicate-name groups "
        f"(DQ002/DQ004/DQ005, see `fix_log`).",
    ]
    lines += [f"- {b}" for b in bullets]
    scr = summary.get("screening")
    if scr:
        a, b = scr["runs"]["raw"], scr["runs"]["clean"]
        da, db = a["at_default_threshold"], b["at_default_threshold"]
        t = a["default_threshold"]

        def op(ev: dict) -> str:
            o = ev["operating_point_95_recall"]
            return (
                f"threshold {o['threshold']} ({o['fp_per_1k_customers']} FP customers per 1k)"
                if o
                else "not reachable in 75–95"
            )

        lines += [
            "",
            f"**Screening experiment** ({scr['synthetic_data']['n_customers']:,} synthetic customers, {scr['synthetic_data']['n_hits']} planted hits "
            f"drawn from the lists, threshold {t}):",
            "",
            "| | Recall | Precision | FP customers / 1k | Alerts | ≥95% recall at |",
            "|---|---:|---:|---:|---:|---|",
            f"| A · raw lists | {da['recall']:.1%} | {da['precision']:.1%} | {da['fp_per_1k_customers']} | {da['alerts']:,} | {op(a)} |",
            f"| B · cleaned lists | {db['recall']:.1%} | {db['precision']:.1%} | {db['fp_per_1k_customers']} | {db['alerts']:,} | {op(b)} |",
            "",
        ]
        delta_recall = db["recall"] - da["recall"]
        delta_fp = db["fp_per_1k_customers"] - da["fp_per_1k_customers"]
        worst = min(b["recall_by_perturbation"].items(), key=lambda kv: kv[1]["recall"])
        verdict = (
            f"Cleaning changed recall by {delta_recall:+.1%} and false-positive customers by {delta_fp:+.1f} per 1k at the same threshold. "
            + (
                "**Trade-off:** the extra recall costs more alerts, because transliterated and normalised names also match more innocent customers. "
                if delta_recall > 0 and delta_fp > 0
                else ""
            )
            + f"The weakest case after cleaning is `{worst[0]}` ({worst[1]['recall']:.0%} recall): dropping middle names removes most of the evidence a name matcher has."
        )
        oa, ob = a["operating_point_95_recall"], b["operating_point_95_recall"]
        if oa and ob:
            verdict += (
                f" Tuned to the same ≥95% recall target, the raw lists need threshold {oa['threshold']} "
                f"({oa['fp_per_1k_customers']} FP customers per 1k) and the cleaned lists threshold {ob['threshold']} "
                f"({ob['fp_per_1k_customers']} per 1k). Comparing at one fixed threshold is misleading; list changes should be "
                "evaluated together with threshold tuning (below-the-line testing)."
            )
        lines.append(verdict)
    lines += [
        "",
        f"![DQ score by list]({image_prefix}/dq_scores.png)",
        f"![Precision vs recall]({image_prefix}/screening/pr_curve.png)",
        f"![Recall by perturbation]({image_prefix}/screening/recall_by_perturbation.png)",
        f"![False positives]({image_prefix}/screening/fp_at_95_recall.png)",
    ]

    return "\n".join(lines)


def update_readme(readme: Path, block: str) -> bool:
    if not readme.exists():
        return False
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        return False
    new = re.sub(
        re.escape(START) + r".*?" + re.escape(END),
        lambda _: f"{START}\n{block}\n{END}",
        text,
        flags=re.S,
    )
    readme.write_text(new, encoding="utf-8")
    return True


def write_report(
    con: duckdb.DuckDBPyConnection,
    ws: Workspace,
    d: date,
    *,
    ingest: dict,
    scorecards: dict,
    crosslist: dict,
    deltas: dict,
    manifests: dict,
    screening: dict | None,
) -> dict:
    out = ws.report_dir(str(d))
    out.mkdir(parents=True, exist_ok=True)
    published = dict(
        con.execute(
            "SELECT source, max(published_date) FROM runs WHERE snapshot_date = ? GROUP BY 1", [d]
        ).fetchall()
    )
    sources = {}
    for s, c in scorecards.items():
        sources[s] = {
            **c,
            "published_date": str(published[s]) if published.get(s) else None,
            "ingest": ingest.get(s, {}),
            "top_issues": _top_issues(c),
        }
    summary = {
        "snapshot_date": str(d),
        "sources": sources,
        "crosslist": {
            "stats": crosslist,
            "transposition_gaps": {t: _gap_stats(con, d, t) for t in ("eu", "uk")},
        },
        "deltas": deltas,
        "exports": {
            k: {
                x: v[x]
                for x in ("record_count", "sha256", "dq_gate_passed", "blocked_sources", "sources")
            }
            for k, v in manifests.items()
        },
        "screening": screening,
    }
    (out / "summary.json").write_text(json.dumps(summary, indent=2, default=str) + "\n")
    (out / "dq_scorecard.json").write_text(json.dumps(scorecards, indent=2, default=str) + "\n")
    (out / "crosslist.json").write_text(
        json.dumps(summary["crosslist"], indent=2, default=str) + "\n"
    )
    (out / "fix_examples.json").write_text(
        json.dumps(_fix_examples(con, d), indent=2, default=str, ensure_ascii=False) + "\n"
    )
    query_frame(
        con, "SELECT * FROM runs WHERE snapshot_date = $d ORDER BY source, started_at", {"d": d}
    ).write_csv(out / "runs.csv")
    _issue_samples(con, d, out / "dq_issues_sample.csv")
    charts.dq_scores(scorecards, out / "dq_scores.png")
    if screening:
        runs = screening["runs"]
        charts.pr_curve(runs, out / "screening" / "pr_curve.png")
        charts.recall_by_perturbation(runs, out / "screening" / "recall_by_perturbation.png")
        charts.fp_comparison(runs, out / "screening" / "fp_at_95_recall.png")
    block = findings_markdown(summary, f"data/reports/{d}")
    (out / "summary.md").write_text(
        f"# sanctions-list-ops: run {d}\n\n{block.replace(f'data/reports/{d}/', '')}\n"
    )
    (ws.reports_dir / "latest.json").write_text(json.dumps({"snapshot_date": str(d)}) + "\n")
    if ws.readme_path is not None:
        summary["readme_updated"] = update_readme(ws.readme_path, block)
    return summary
